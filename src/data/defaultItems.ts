import type { PackingItem } from '../types';

/** Skrót do tworzenia wpisów: klucze assignments = kategorie, wartości = ilości */
function item(
  id: string,
  personId: string,
  name: string,
  svgKey: string,
  emoji: string,
  assignments: Record<string, number>,
  aiImage?: string,
): PackingItem {
  return {
    id,
    personId,
    name,
    svgKey,
    emoji,
    categoryIds: Object.keys(assignments),
    quantities: assignments,
    packedIn: [],
    aiImage,
  };
}

